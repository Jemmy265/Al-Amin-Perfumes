/* Guards that the redesign kept the original recommendation behaviour.
   legacy-golden.json was generated by running the ORIGINAL js/script.js
   (quizResults + similarTo) against the original js/data.js. */
import { describe, expect, it } from "vitest";
import golden from "../__fixtures__/legacy-golden.json";
import { SEED_PRODUCTS } from "../../data/seed/products";
import { SEED_SETTINGS } from "../../data/seed/content";
import { QUIZ, quizResults, type QuizAnswers } from "../quiz";
import { similarTo } from "../similar";

const products = [...SEED_PRODUCTS].sort((a, b) => a.sortOrder - b.sortOrder);
const best = SEED_SETTINGS.bestSellers;

describe("quiz parity with the original site", () => {
  const entries = Object.entries(golden.quiz as Record<string, string[]>);
  it("covers every answer combination", () => {
    expect(entries.length).toBe(QUIZ.reduce((n, q) => n * q.options.length, 1));
  });
  it.each(entries)("%s", (key, expected) => {
    const [who, use, scent, strength] = key.split("|");
    const got = quizResults(products, { who, use, scent, strength } as QuizAnswers, best).map((p) => p.id);
    expect(got).toEqual(expected);
  });
});

describe("similar perfumes parity", () => {
  it.each(Object.entries(golden.similar as Record<string, string[]>))("%s", (id, expected) => {
    const p = products.find((x) => x.id === id)!;
    expect(similarTo(p, products, best).map((x) => x.id)).toEqual(expected);
  });
});
