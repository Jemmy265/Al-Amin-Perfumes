/* Generates worker/migrations/0002_seed.sql from the storefront's real data
   (src/data/seed). Run: node scripts/gen-seed-sql.ts
   The original photos stay static assets (assets/products/<file>), served by
   Cloudflare without invoking the Worker; only new uploads go to R2. */
import { writeFileSync } from "node:fs";
import { SEED_PRODUCTS } from "../src/data/seed/products.ts";
import { LABELS, SEED_CONTENT, SEED_SETTINGS } from "../src/data/seed/content.ts";

const q = (v: string | number | null) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);
const products = [...SEED_PRODUCTS].sort((a, b) => a.sortOrder - b.sortOrder);
const lines: string[] = [
  "-- Seed: the real Al-Amin catalog and site content (generated by scripts/gen-seed-sql.ts).",
  "-- Safe to run once on an empty database.",
];

products.forEach((p, i) => {
  const rank = SEED_SETTINGS.bestSellers.indexOf(p.id);
  const n = p.notes;
  lines.push(
    `INSERT INTO products (id, name, name_en, house, label, is_new, category, intensity, status, family, year, perfumer, notes_top, notes_heart, notes_base, notes_all, sort_order, featured_rank) VALUES (` +
      [p.id, p.name, p.nameEn, p.house, p.label, p.isNew ? 1 : 0, p.tags.audience, p.tags.intensity, "published",
        p.family, p.year, p.perfumer, n.top ?? "", n.heart ?? "", n.base ?? "", n.all ?? "", i + 1, rank >= 0 ? rank + 1 : null]
        .map((v) => q(v as string | number | null)).join(", ") + ");",
  );
  for (const [size, price] of Object.entries(p.prices))
    lines.push(`INSERT INTO product_variants (product_id, size_ml, price) VALUES (${q(p.id)}, ${size}, ${price});`);
  p.tags.scents.forEach((t, k) => lines.push(`INSERT INTO product_tags (product_id, tag_group, tag, position) VALUES (${q(p.id)}, 'scent', ${q(t)}, ${k});`));
  p.tags.occasions.forEach((t, k) => lines.push(`INSERT INTO product_tags (product_id, tag_group, tag, position) VALUES (${q(p.id)}, 'occasion', ${q(t)}, ${k});`));
  const file = p.image.split("/").pop()!;
  lines.push(`INSERT INTO product_images (product_id, object_key, alt_text, sort_order) VALUES (${q(p.id)}, ${q(`assets/products/${file}`)}, ${q(`${p.name} — ${p.nameEn}`)}, 0);`);
});

for (const [key, value] of Object.entries({ settings: SEED_SETTINGS, content: SEED_CONTENT, labels: LABELS }))
  lines.push(`INSERT INTO site_kv (key, value) VALUES (${q(key)}, ${q(JSON.stringify(value))});`);

writeFileSync(new URL("../worker/migrations/0002_seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`Wrote ${products.length} products to worker/migrations/0002_seed.sql`);
